const assert = require("node:assert/strict");
const fs = require("node:fs");
const ts = require("typescript");
const THREE = require("three");
const draws = [];
const transforms = [];
const context = { setTransform: (...args) => transforms.push(args), clearRect() {}, drawImage: (...args) => draws.push(args) };
let removed = false;
const canvas = { width: 0, height: 0, style: {}, getContext: () => context, setAttribute() {}, remove: () => { removed = true; } };
const document = { createElement: () => canvas };
const window = { devicePixelRatio: 2 };
const host = { clientWidth: 1000, clientHeight: 600, appendChild: (child) => assert.equal(child, canvas) };
const exportsObject = {};
const js = ts.transpileModule(fs.readFileSync("app/components/tower-defense/scene/label-overlay.ts", "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS },
}).outputText;
new Function("require", "exports", "document", "window", js)(require, exportsObject, document, window);
const overlay = exportsObject.createLabelOverlay(host);
const camera = new THREE.PerspectiveCamera(45, 1000 / 600, 0.1, 1000);
camera.position.z = 50;
const texture = new THREE.CanvasTexture({ width: 256, height: 256 });
const sprite = new THREE.Sprite(new THREE.SpriteMaterial({ map: texture }));
sprite.userData.screenWidth = sprite.userData.screenHeight = 24;
const group = new THREE.Group(); group.scale.setScalar(5); group.add(sprite);
overlay.draw(camera, [sprite]);
assert.equal(canvas.width, 2000, "HUD buffer follows display DPR, not the low-res WebGL buffer");
assert.equal(canvas.height, 1200);
assert.deepEqual(transforms.at(-1), [2, 0, 0, 2, 0, 0]);
assert.deepEqual(draws.at(-1).slice(1), [488, 288, 24, 24]);
assert.equal(sprite.material.opacity, 0, "do not double render a low-resolution WebGL badge");
assert.equal(canvas.style.pointerEvents, "none", "overlay must preserve tower picking/camera controls");
camera.zoom = 3; camera.updateProjectionMatrix();
overlay.draw(camera, [sprite]);
assert.deepEqual(draws.at(-1).slice(1), [488, 288, 24, 24]);
const count = draws.length;
group.visible = false; overlay.draw(camera, [sprite]);
assert.equal(draws.length, count);
group.visible = true; sprite.position.z = 20; group.updateMatrixWorld(true);
overlay.draw(camera, [sprite]);
assert.equal(draws.length, count, "hide labels behind the camera");
overlay.draw(camera, []);
assert.equal(sprite.material.opacity, 1, "release removed sprites");
overlay.dispose(); assert.ok(removed);
console.log("PASS: high-DPI HUD independent of WebGL resolution, stable zoom sizing, visibility, picking and cleanup");
